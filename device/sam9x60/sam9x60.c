static int oled_splash(void) {
    for (int i = 0; i < sizeof(oled_init_cmds); i++) {
        int ret = twi_write(0, 0x3C, 0x00, 1, &oled_init_cmds[i], 1);
        if (ret) {
            dbg_info("OLED init failed: %d : 0x%02X\n", i, oled_init_cmds[i]);
            return ret;
        }
    }
    // calc offset
    unsigned char oled_first_byte = 0;
    twi_read(0, 0x3C, 0x00, 1, &oled_first_byte, 1);
    dbg_info("OLED Initialized! 0x%02X\n", oled_first_byte);
    unsigned char offset = (oled_first_byte == 0x28 || oled_first_byte == 0x16) ? 2 : 0;
    // draw logo
    for (int page = 0; page < 8; page++) {
        unsigned char cmd[] = {0xB0 + page, offset, 0x10};
        int ret = twi_write(0, 0x3C, 0x00, 1, cmd, sizeof(cmd));
        if (ret) {
            dbg_info("OLED page command fail: %d\n", page);
            return ret;
        }
        ret = twi_write(0, 0x3C, 0x40, 1, &logo[page*128], 128);
        if (ret) {
            dbg_info("OLED page data fail: %d\n", page);
            return ret;
        } 
    }
    dbg_info("OLED Splash Done\n");
    return 0;
}

static inline unsigned int spi_readl(unsigned int reg)
{
	return readl(reg);
}

static inline void spi_writel(unsigned int reg, unsigned int value)
{
	writel(value, reg);
}

static void spi_write_data(unsigned int base, unsigned short data)
{
	while ((spi_readl(base + SPI_SR) & AT91C_SPI_TXEMPTY) == 0);
	spi_writel(base + SPI_TDR, data);
	while ((spi_readl(base + SPI_SR) & AT91C_SPI_TDRE) == 0);
}

